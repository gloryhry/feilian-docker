#!/usr/bin/env python3
"""Generate a fail-closed nginx management gateway; never read secret contents.

nginx authenticates every HTTP/WebSocket path and proxies only to websockify's
Unix socket. No unauthenticated TCP backend, HTTP redirect or TLS bypass exists.
The supervisor owns process startup and /run/feilian-web/novnc.sock permissions.
"""
from __future__ import annotations

import argparse
import ipaddress
import os
from pathlib import Path
import re
import stat
import sys
import tempfile


class GatewayError(ValueError):
    pass


PATH = re.compile(r"/[A-Za-z0-9_./+-]+\Z")


def _path(value):
    path = Path(value).absolute()
    if not PATH.fullmatch(str(path)) or path.resolve() != path:
        raise GatewayError("gateway paths must be absolute literals without symlinks")
    return path


def _address(key, value):
    try:
        address = ipaddress.ip_address(value)
    except ValueError:
        raise GatewayError("{} must be a literal IP address".format(key)) from None
    if address.is_multicast:
        raise GatewayError("multicast listeners are forbidden")
    return address


def _loopback(address):
    return (getattr(address, "ipv4_mapped", None) or address).is_loopback


def _port(value):
    if not re.fullmatch(r"[0-9]{1,5}", value) or not 1 <= int(value) <= 65535:
        raise GatewayError("invalid management listener port")
    return str(int(value))


def _regular(path, mode, check_owner):
    try:
        details = path.lstat()
    except OSError:
        raise GatewayError("required secret file is missing") from None
    if not stat.S_ISREG(details.st_mode) or details.st_nlink != 1:
        raise GatewayError("secret files must be regular, unlinked files")
    actual_mode = stat.S_IMODE(details.st_mode)
    if actual_mode & ~mode or not actual_mode & 0o400:
        raise GatewayError("secret file permissions are unsafe")
    if path.name == "web.htpasswd" and not actual_mode & 0o040:
        raise GatewayError("web authentication file must be readable by www-data")
    if check_owner and details.st_uid != 0:
        raise GatewayError("secret files must be owned by root")
    if check_owner and path.name == "web.htpasswd" and details.st_gid != 33:
        raise GatewayError("web authentication file requires www-data group")


def render_config(environ, state_dir, secrets_dir, check_owner=True):
    state, secrets = _path(state_dir), _path(secrets_dir)
    mode = environ.get("FEILIAN_NETWORK_MODE", environ.get("NET_MODE", "bridge"))
    if mode == "auto":
        mode = "bridge"
    if mode not in {"bridge", "host", "macvlan"}:
        raise GatewayError("unsupported network mode")
    auth, tls = environ.get("WEB_AUTH", "1"), environ.get("WEB_TLS", "off")
    if auth not in {"0", "1"} or tls not in {"off", "selfsigned", "provided"}:
        raise GatewayError("invalid web authentication or TLS mode")
    external = _address("WEB_BIND", environ.get("WEB_BIND", "127.0.0.1"))
    bind = _address("NOVNC_BIND", environ.get("NOVNC_BIND", "127.0.0.1" if mode == "host" else "0.0.0.0"))
    port = _port(environ.get("NOVNC_HOST_PORT", environ.get("NOVNC_PORT", "6080")) if mode == "host"
                 else environ.get("NOVNC_INTERNAL_PORT", environ.get("NOVNC_PORT", "6080")))
    cidrs = []
    raw = environ.get("WEB_SOURCE_CIDRS", "")
    for item in raw.split(",") if raw else []:
        try:
            net = ipaddress.ip_network(item, strict=True)
        except ValueError:
            raise GatewayError("invalid web source CIDR") from None
        if net.prefixlen == 0 or net.is_multicast or net.is_unspecified or net in cidrs:
            raise GatewayError("unsafe or duplicate web source CIDR")
        cidrs.append(net)
    if mode == "host" and (not _loopback(external) or not _loopback(bind)):
        raise GatewayError("host management listeners must be loopback")
    if (mode == "macvlan" or not _loopback(external)) and not (auth == "1" and tls != "off" and cidrs):
        raise GatewayError("LAN management requires authentication, TLS and source CIDRs")
    if auth == "1":
        _regular(secrets / "web.htpasswd", 0o640, check_owner)
    if tls != "off":
        _regular(secrets / "tls.crt", 0o644, check_owner)
        _regular(secrets / "tls.key", 0o600, check_owner)
    listen = "[{}]".format(bind) if bind.version == 6 else str(bind)
    lines = [
        "# Generated by Feilian; no secret values are present in this file.",
        "user www-data;", "worker_processes 1;", "daemon off;",
        "pid {}/nginx.pid;".format(state), "error_log stderr warn;",
        "events { worker_connections 128; }", "http {",
        "  include /etc/nginx/mime.types;", "  default_type application/octet-stream;",
        "  access_log off;", "  server_tokens off;",
        "  client_body_temp_path {}/client-body;".format(state),
        "  proxy_temp_path {}/proxy-temp;".format(state),
        "  map $http_upgrade $connection_upgrade { default upgrade; '' close; }",
        "  upstream feilian_novnc { server unix:" + str(state / "novnc.sock") + "; }",
        "  server {", "    listen {}:{}{};".format(listen, port, " ssl" if tls != "off" else ""),
        "    server_name _;", "    client_max_body_size 1k;",
        "    add_header X-Content-Type-Options nosniff always;",
        "    add_header Referrer-Policy no-referrer always;", "    satisfy all;",
    ]
    if auth == "1":
        lines += ['    auth_basic "Feilian";', "    auth_basic_user_file {};".format(secrets / "web.htpasswd")]
    if cidrs:
        lines += ["    allow {};".format(net) for net in cidrs] + ["    deny all;"]
    if tls != "off":
        lines += ["    ssl_certificate {};".format(secrets / "tls.crt"),
                  "    ssl_certificate_key {};".format(secrets / "tls.key"),
                  "    ssl_protocols TLSv1.2 TLSv1.3;", "    ssl_session_tickets off;"]
    lines += [
        "    location / {", "      limit_except GET HEAD { deny all; }",
        "      proxy_pass http://feilian_novnc;", "      proxy_http_version 1.1;",
        "      proxy_set_header Upgrade $http_upgrade;",
        "      proxy_set_header Connection $connection_upgrade;",
        "      proxy_set_header Host $host;", '      proxy_set_header Authorization "";',
        '      proxy_set_header X-Forwarded-For "";', "      proxy_buffering off;",
        "      proxy_read_timeout 3600s;", "    }", "  }", "}", "",
    ]
    return "\n".join(lines)


def prepare(environ=None, state_dir="/run/feilian-web", secrets_dir="/run/feilian-secrets", check_owner=True):
    env = os.environ if environ is None else environ
    state = _path(state_dir)
    if state == Path("/run/feilian") or state == _path(secrets_dir):
        raise GatewayError("web state must not reuse controller or secrets directories")
    # Fully validate before creating/replacing any runtime artifacts.
    text = render_config(env, state, secrets_dir, check_owner=check_owner)
    state.mkdir(mode=0o2750, parents=True, exist_ok=True)
    os.chmod(state, 0o2750)
    if check_owner:
        os.chown(state, 0, 33)
    for name in ("client-body", "proxy-temp"):
        folder = _path(state / name)
        folder.mkdir(mode=0o770, exist_ok=True)
        os.chmod(folder, 0o770)
        if check_owner:
            os.chown(folder, 0, 33)
    target = state / "nginx.conf"
    if target.is_symlink():
        raise GatewayError("refusing symlink nginx configuration")
    temporary = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=state, prefix=".nginx-", delete=False) as handle:
            temporary = Path(handle.name)
            os.chmod(temporary, 0o640)
            if check_owner:
                os.chown(temporary, 0, 33)
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        if _path(state) != state or target.is_symlink():
            raise GatewayError("gateway state target changed")
        os.replace(temporary, target)
        temporary = None
    finally:
        if temporary is not None and temporary.parent.resolve() == state:
            temporary.unlink(missing_ok=True)
    return target


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("prepare",))
    parser.add_argument("--state-dir", default="/run/feilian-web")
    parser.add_argument("--secrets-dir", default="/run/feilian-secrets")
    args = parser.parse_args(argv)
    try:
        path = prepare(state_dir=args.state_dir, secrets_dir=args.secrets_dir)
    except (GatewayError, OSError):
        print("feilian web: gateway preparation failed; check configuration and secret permissions", file=sys.stderr)
        return 2
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
